import AppKit

/// One type/data pair of a pasteboard item, e.g. `public.utf8-plain-text` and its bytes.
struct PasteboardRepresentation: Equatable, Sendable {
    let type: String
    let data: Data
}

/// One pasteboard item: its representations in the order the source app offered them.
typealias PasteboardItemData = [PasteboardRepresentation]

/// Marker types apps put on the pasteboard to describe the content (nspasteboard.org).
/// They are read for filtering and never stored.
enum PasteboardMarkers {
    static let concealed = "org.nspasteboard.ConcealedType"
    static let transient = "org.nspasteboard.TransientType"
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    static let source = "org.nspasteboard.source"
    /// Older or app-specific transient markers.
    static let legacyTransient = ["de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
                                  "Pasteboard generator type"]
    /// Added to everything ClipVault writes, so its own writes are never captured.
    static let own = "com.georgecristea.ClipVault.marker"

    /// Any of these means "do not save".
    static let skip: Set<String> = Set([concealed, transient, autoGenerated, own] + legacyTransient)
    private static let all: Set<String> = skip.union([source, "com.apple.is-remote-clipboard"])

    /// Types never stored: markers, and Office/OLE link types that only work while the source
    /// document is open.
    static func isStorable(_ type: String) -> Bool {
        if all.contains(type) { return false }
        return !["com.microsoft.ObjectLink", "com.microsoft.Link-Source", "com.microsoft.ole.source",
                 "com.microsoft.DataObject", "com.microsoft.Embed-Source", "com.microsoft.Object-Descriptor"]
            .contains { type.hasPrefix($0) }
    }
}

/// Everything read from the pasteboard, before filtering and classification.
struct PasteboardSnapshot: Equatable {
    var items: [PasteboardItemData]
    /// Every type present, markers included.
    var types: Set<String>
    /// The source app declared with `org.nspasteboard.source`, if any.
    var declaredSource: String?

    /// Reads every item and storable type. Types that would take the clip past `maxBytes` are
    /// skipped.
    static func read(_ pasteboard: NSPasteboard, maxBytes: Int) -> PasteboardSnapshot {
        var items: [PasteboardItemData] = []
        var types = Set<String>()
        var declaredSource: String?
        var total = 0
        for pbItem in pasteboard.pasteboardItems ?? [] {
            var item: PasteboardItemData = []
            for type in pbItem.types {
                types.insert(type.rawValue)
                if type.rawValue == PasteboardMarkers.source { declaredSource = pbItem.string(forType: type) }
                guard PasteboardMarkers.isStorable(type.rawValue), let data = pbItem.data(forType: type),
                      total + data.count <= maxBytes else { continue }
                total += data.count
                item.append(PasteboardRepresentation(type: type.rawValue, data: data))
            }
            if !item.isEmpty { items.append(item) }
        }
        return PasteboardSnapshot(items: items, types: types, declaredSource: declaredSource)
    }
}
