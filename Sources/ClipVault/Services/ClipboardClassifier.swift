import AppKit

/// Minimal read surface of a pasteboard, so capture classification is unit-testable with a fake.
protocol PasteboardReading {
    func string(forType type: NSPasteboard.PasteboardType) -> String?
    func data(forType type: NSPasteboard.PasteboardType) -> Data?
    func fileURLs() -> [URL]
    func typeIdentifiers() -> [String]
}

/// Pure pasteboard → ClipboardCapture classification. Order: files, then image, then text.
enum ClipboardClassifier {
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    static func shouldIgnore(_ pasteboard: PasteboardReading) -> Bool {
        !ignoredTypes.isDisjoint(with: Set(pasteboard.typeIdentifiers()))
    }

    static func capture(from pasteboard: PasteboardReading) -> ClipboardCapture? {
        fileCapture(from: pasteboard)
            ?? imageCapture(from: pasteboard)
            ?? textCapture(from: pasteboard)
    }

    static func textCapture(from pasteboard: PasteboardReading) -> ClipboardCapture? {
        guard let text = pasteboard.string(forType: .string), !text.isEmpty,
              let data = text.data(using: .utf8) else {
            return nil
        }
        return ClipboardCapture(
            kind: .text,
            data: data,
            preview: text.clipVaultPreview(maxLength: 240),
            fileExtension: "txt")
    }

    static func imageCapture(from pasteboard: PasteboardReading) -> ClipboardCapture? {
        if let data = pasteboard.data(forType: .png), let image = NSImage(data: data) {
            return ClipboardCapture(kind: .image, data: data, preview: image.clipVaultDescription, fileExtension: "png")
        }
        if let data = pasteboard.data(forType: .tiff),
           let image = NSImage(data: data),
           let pngData = image.clipVaultPNGData {
            return ClipboardCapture(kind: .image, data: pngData, preview: image.clipVaultDescription, fileExtension: "png")
        }
        return nil
    }

    static func fileCapture(from pasteboard: PasteboardReading) -> ClipboardCapture? {
        let urls = pasteboard.fileURLs()
        guard !urls.isEmpty else { return nil }
        let paths = urls.map(\.path)
        guard let data = try? JSONEncoder().encode(paths) else { return nil }

        let preview = paths.count == 1
            ? URL(fileURLWithPath: paths[0]).lastPathComponent
            : "\(paths.count) files"

        return ClipboardCapture(kind: .files, data: data, preview: preview, fileExtension: "json")
    }
}

/// Adapter exposing the live `NSPasteboard` through `PasteboardReading`.
struct NSPasteboardReader: PasteboardReading {
    let pasteboard: NSPasteboard

    func string(forType type: NSPasteboard.PasteboardType) -> String? {
        pasteboard.string(forType: type)
    }

    func data(forType type: NSPasteboard.PasteboardType) -> Data? {
        pasteboard.data(forType: type)
    }

    func fileURLs() -> [URL] {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        let objects = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [NSURL]
        return objects?.compactMap { $0 as URL } ?? []
    }

    func typeIdentifiers() -> [String] {
        pasteboard.types?.map(\.rawValue) ?? []
    }
}

extension String {
    func clipVaultPreview(maxLength: Int) -> String {
        let collapsed = components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
        guard collapsed.count > maxLength else { return collapsed }
        let endIndex = collapsed.index(collapsed.startIndex, offsetBy: maxLength)
        return String(collapsed[..<endIndex]) + "..."
    }
}

extension NSImage {
    var clipVaultPNGData: Data? {
        guard let tiffRepresentation,
              let bitmap = NSBitmapImageRep(data: tiffRepresentation) else {
            return nil
        }
        return bitmap.representation(using: .png, properties: [:])
    }

    var clipVaultDescription: String {
        let width = Int(size.width.rounded())
        let height = Int(size.height.rounded())
        return "\(width) x \(height) image"
    }
}
